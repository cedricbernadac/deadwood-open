export function getLanguage() { return language; }
export function setLanguage(value) {
  const next = validLanguage(value), changed = next !== language;
  language = next;
  try { globalThis.localStorage?.setItem(STORAGE_KEY, next); } catch {}
  if (globalThis.document?.documentElement) document.documentElement.lang = next;
  translateDom();
  if (changed && globalThis.window?.dispatchEvent && typeof CustomEvent === 'function') {
    window.dispatchEvent(new CustomEvent('deadwood-language-change', { detail: { language: next } }));
  }
  return next;
}
export function t(key, params = {}) {
  const entry = text[key], template = entry?.[language === 'en' ? 1 : 0] ?? key;
  // Callers use textContent / setAttribute. Parameter text is never HTML.
  return template.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(params, name) ? String(params[name]) : match);
}
// French «de» before a name, elided before a vowel or a mute h: «de Léa»,
// «d’Inès», «d’Hugo», «d’Yves»; a y before a vowel is a consonant: «de Yann».
export function frenchOf(name) {
  const value = String(name ?? ''), plain = value.normalize('NFD').replace(/\p{M}/gu, '').toLowerCase();
  return `${/^([aeiouæœ]|h[aeiouy]|y[^aeiouy\s])/.test(plain) ? 'd’' : 'de '}${value}`;
}
export function weaponLabel(id, { short = false, language: locale = getLanguage() } = {}) {
  const english = locale === 'en';
  if (short && id === 'rifle') return english ? 'MG' : 'MITRAILLEUSE';
  if (short && id === 'shotgun') return english ? 'SHOTGUN' : 'POMPE';
  if (short && id === 'smg') return english ? 'SMG' : 'PM';
  if (short && id === 'magnum') return 'MAGNUM';
  if (short && id === 'assault') return english ? 'AR' : 'ASSAUT';
  return weapons[id]?.[english ? 1 : 0] ?? String(id);
}
