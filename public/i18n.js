export function translateMessage(value) {
  const source = String(value ?? '');
  if (language !== 'en') return source;
  if (exact.has(source)) return exact.get(source);
  for (const [pattern, render] of patterns) {
    const match = source.match(pattern);
    if (match) return render(...match);
  }
  return source;
}

export function translateDom(root = globalThis.document) {
  if (!root?.querySelectorAll) return;
  if (globalThis.document?.documentElement) document.documentElement.lang = language;
  for (const [attribute, target] of [
    ['data-i18n', null], ['data-i18n-placeholder', 'placeholder'],
    ['data-i18n-aria-label', 'aria-label'], ['data-i18n-title', 'title'],
  ]) {
    const nodes = [...root.querySelectorAll(`[${attribute}]`)];
    if (root.matches?.(`[${attribute}]`)) nodes.unshift(root);
    for (const node of nodes) {
      const translated = t(node.getAttribute(attribute));
      if (target) node.setAttribute(target, translated); else node.textContent = translated;
    }
  }
  const selector = root.querySelector?.('#language-select');
  if (selector) selector.value = language;
}
